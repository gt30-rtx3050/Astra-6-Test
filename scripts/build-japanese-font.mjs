import fs from "node:fs";
import path from "node:path";
function sourceText(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .map((e) =>
      e.isDirectory()
        ? sourceText(path.join(dir, e.name))
        : /\.(jsx|js)$/.test(e.name)
          ? fs.readFileSync(path.join(dir, e.name), "utf8")
          : "",
    )
    .join("");
}
const chars = [
  ...new Set(
    [...sourceText("src")]
      .map((c) => c.codePointAt(0))
      .filter((n) => n >= 0x3000 && n <= 0x9fff),
  ),
];
const css = fs.readFileSync(
  "node_modules/@fontsource/noto-sans-jp/400.css",
  "utf8",
);
const faces = [];
for (const face of css.matchAll(/@font-face\s*\{([\s\S]*?)\}/g)) {
  const range = face[1].match(/unicode-range:([^;]+);/);
  if (!range) continue;
  const ranges = range[1].split(",").map((x) =>
    x
      .trim()
      .replace("U+", "")
      .split("-")
      .map((h) => parseInt(h, 16)),
  );
  const used = chars.filter((n) =>
    ranges.some(([lo, hi = lo]) => n >= lo && n <= hi),
  );
  if (!used.length) continue;
  const file = face[1].match(/url\(\.\/files\/([^)]*\.woff2)\)/)[1];
  faces.push(
    `@font-face {font-family:'Noto Sans JP';font-style:normal;font-weight:400;font-display:swap;src:url('../node_modules/@fontsource/noto-sans-jp/files/${file}') format('woff2');unicode-range:${used.map((n) => "U+" + n.toString(16)).join(",")};}`,
  );
}
fs.writeFileSync(
  "src/japanese-font.css",
  "/* Generated by npm run fonts. Only Japanese label ranges used in source. */\n" +
    faces.join("\n") +
    "\n",
);
console.log(
  `${faces.length} font segments for ${chars.length} Japanese characters`,
);
